/// One machine: a clone of a bare origin with the release 3.2.0, a
/// fake `gh`, and a riff-server.
struct Machine {
    env: Isolated,
    root: tempfile::TempDir,
    server: String,
}

impl Machine {
    async fn new() -> Machine {
        let root = tempfile::tempdir().unwrap();
        let origin = root.path().join("como-technologies/riff.git");
        std::fs::create_dir_all(&origin).unwrap();
        git(&origin, &["init", "-q", "--bare", "-b", "main"]);
        let clone = root.path().join("clone");
        std::fs::create_dir_all(clone.join("deploy")).unwrap();
        std::fs::create_dir_all(root.path().join("bin")).unwrap();
        git(&clone, &["init", "-q", "-b", "main"]);
        for args in [
            &["config", "user.name", "Test"][..],
            &["config", "user.email", "test@example.com"],
            &["remote", "add", "origin", &origin.to_string_lossy()],
        ] {
            git(&clone, args);
        }
        let write = |name: &str, content: &str| std::fs::write(clone.join(name), content).unwrap();
        write(
            "Cargo.toml",
            "[workspace]\nmembers = [\"crates/*\"]\n\n[workspace.package]\nversion = \"3.2.0\"\n",
        );
        write("Cargo.lock", LOCK);
        std::fs::copy(
            top().join("deploy/release-check.sh"),
            clone.join("deploy/release-check.sh"),
        )
        .unwrap();
        git(&clone, &["add", "-A"]);
        git(&clone, &["commit", "-q", "-m", "Release v3.2.0"]);
        git(&clone, &["tag", "-a", "v3.2.0", "-m", "Release v3.2.0"]);
        write("change.txt", "a change\n");
        git(&clone, &["add", "-A"]);
        git(&clone, &["commit", "-q", "-m", "Show the line (#41)"]);
        git(&clone, &["push", "-q", "origin", "main", "v3.2.0"]);
        let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
        let addr = listener.local_addr().unwrap();
        tokio::spawn(async move { axum::serve(listener, riff_server::router()).await.unwrap() });
        let machine = Machine {
            env: Isolated::new(),
            root,
            server: format!("http://{addr}"),
        };
        machine.fake_gh("");
        machine
    }

    fn clone(&self) -> PathBuf {
        self.root.path().join("clone")
    }

    fn origin(&self) -> PathBuf {
        self.root.path().join("como-technologies/riff.git")
    }

    fn bin(&self) -> PathBuf {
        self.root.path().join("bin")
    }

    fn head(&self) -> String {
        git(&self.clone(), &["rev-parse", "HEAD"])
    }

    /// A fake `gh` that logs `gh ARGS`, copies its stdin for
    /// `--body-file -` and `--notes-file -`, and the file of `--input`,
    /// and answers with `cases` first, then with the facts of the
    /// release 3.2.0.
    fn fake_gh(&self, cases: &str) {
        let head = self.head();
        let merged = format!(
            r#"[{{"number":41,"title":"Show the line","body":"Closes #12\n\nIssue: #12\nMilestone: Wave 34\n","milestone":{{"title":"Wave 34: Release"}},"labels":[],"mergeCommit":{{"oid":"{head}"}}}},{{"number":30,"title":"Old","body":"","milestone":{{"title":"Wave 32"}},"labels":[],"mergeCommit":{{"oid":"0000"}}}}]"#
        );
        isolated::write_program(
            self.bin().join("gh"),
            format!(
                "#!/bin/sh\ndir=$(dirname \"$0\")\necho \"gh $*\" >> \"$dir/gh.log\"\n\
                 case \"$*\" in *'-file -'*) cat >> \"$dir/gh.log\" ;; esac\n\
                 case \"$*\" in *'--input '*) cat \"$7\" >> \"$dir/gh.log\"; echo >> \"$dir/gh.log\" ;; esac\n\
                 case \"$*\" in\n{cases}\n\
                 'release list'*) printf '%s\n' '[{{\"tagName\":\"v3.2.0\"}},{{\"tagName\":\"v3.0.0\"}}]' ;;\n\
                 'api repos/{{owner}}/{{repo}}/milestones'*) printf '%s\n' '[{{\"number\":40,\"title\":\"Wave 34: Release\",\"open_issues\":2,\"closed_issues\":0}},{{\"number\":3,\"title\":\"Backlog\",\"open_issues\":1,\"closed_issues\":0}}]' ;;\n\
                 'issue list'*) printf '%s\n' '[]' ;;\n\
                 'issue create'*) printf '%s\n' 'https://github.com/como-technologies/riff/issues/7' ;;\n\
                 'pr list --state merged --base main'*) printf '%s\n' '{merged}' ;;\n\
                 'pr list --state merged --label release'*) printf '%s\n' '[]' ;;\n\
                 'pr create'*) printf '%s\n' 'https://github.com/como-technologies/riff/pull/1140' ;;\n\
                 'run list --workflow CI --status waiting'*) printf '%s\n' '[]' ;;\n\
                 'pr list --state open --label release'*) printf '%s\n' '[]' ;;\n\
                 'run list --workflow CI --limit'*) printf '%s\n' '[]' ;;\n\
                 'api repos/{{owner}}/{{repo}}/commits/'*) printf '%s\n' '{{\"statuses\":[]}}' ;;\n\
                 esac\nexit 0\n"
            ),
        );
    }

    fn log(&self) -> String {
        std::fs::read_to_string(self.bin().join("gh.log")).unwrap_or_default()
    }

    /// `riff ARGS` in the clone, with the fake `gh` first in `PATH`, and
    /// `vars` in its environment.
    async fn run(&self, vars: &[(&str, &str)], args: &[&str], stdin: &str) -> Output {
        let path = format!(
            "{}:{}",
            self.bin().display(),
            std::env::var("PATH").unwrap()
        );
        let mut cmd = self.env.riff();
        cmd.args(args)
            .current_dir(self.clone())
            .env("RIFF_SERVER", &self.server)
            .env("RIFF_USER", "mike")
            .env("RIFF_HOST", "thelio")
            .env("GIT_CONFIG_GLOBAL", "/dev/null")
            .env("PATH", path)
            .env_remove("CLAUDECODE")
            .stdin(Stdio::piped());
        for (key, value) in vars {
            cmd.env(key, value);
        }
        let stdin = stdin.to_owned();
        tokio::task::spawn_blocking(move || {
            let mut child = cmd
                .stdout(Stdio::piped())
                .stderr(Stdio::piped())
                .spawn()
                .unwrap();
            use std::io::Write;
            child
                .stdin
                .take()
                .unwrap()
                .write_all(stdin.as_bytes())
                .unwrap();
            child.wait_with_output().unwrap()
        })
        .await
        .unwrap()
    }

    async fn ok(&self, vars: &[(&str, &str)], args: &[&str]) -> String {
        let out = self.run(vars, args, "").await;
        assert!(out.status.success(), "riff {args:?}: {}", text(&out.stderr));
        text(&out.stdout)
    }
}

#[tokio::test]
async fn cut_pushes_the_branch_and_opens_the_release_pull_request() {
    let machine = Machine::new().await;
    let out = machine
        .ok(&[], &["release", "cut", "3.3.0", "--why", "New commands."])
        .await;
    assert_eq!(
        out,
        "The release pull request #1140 for issue #7, with auto-merge on: \
         https://github.com/como-technologies/riff/pull/1140\nnext: wait for the verify and the merge of pull request #1140\n"
    );
    let branch = git(&machine.origin(), &["show", "release-v3.3.0:Cargo.toml"]);
    assert!(branch.contains("version = \"3.3.0\""), "{branch}");
    let lock = git(&machine.origin(), &["show", "release-v3.3.0:Cargo.lock"]);
    assert!(
        lock.contains("name = \"riff-server\"\nversion = \"3.3.0\""),
        "{lock}"
    );
    assert!(
        lock.contains("name = \"serde\"\nversion = \"1.0.229\""),
        "{lock}"
    );
    let subject = git(
        &machine.origin(),
        &["log", "-1", "--format=%s", "release-v3.3.0"],
    );
    assert_eq!(subject, "Release v3.3.0");
    let log = machine.log();
    assert!(
        log.contains("gh issue create --title Release v3.3.0 --label release --milestone Wave 34: Release --body-file -"),
        "{log}"
    );
    assert!(
        log.contains(
            "gh pr create --head release-v3.3.0 --base main --title Release v3.3.0 --label release \
             --milestone Wave 34: Release --body-file -\nRefs #7\n\nPart of #7: the release pull request."
        ),
        "{log}"
    );
    assert!(
        log.contains("Level: minor, 3.3.0. New commands.\n"),
        "{log}"
    );
    assert!(
        log.contains("Waves in this release: Wave 34: Release.\n"),
        "{log}"
    );
    assert!(log.contains("- #12: Show the line (#41).\n"), "{log}");
    assert!(!log.contains("#30"), "{log}");
    assert!(!log.contains("Closes #7"), "{log}");
    assert!(log.contains("gh pr merge 1140 --auto --squash"), "{log}");
    // The worktree of the cut is gone.
    assert_eq!(
        git(&machine.clone(), &["worktree", "list"]).lines().count(),
        1
    );
}

#[tokio::test]
async fn cut_refuses_an_old_version_and_a_version_on_main_with_no_release() {
    let machine = Machine::new().await;
    let out = machine.run(&[], &["release", "cut", "3.2.0"], "").await;
    assert!(!out.status.success());
    assert!(
        text(&out.stderr).contains("3.2.0 is not newer than the last release v3.2.0"),
        "{}",
        text(&out.stderr)
    );

    // origin/main has 3.3.0, and 3.3.0 has no release.
    let clone = machine.clone();
    let toml = std::fs::read_to_string(clone.join("Cargo.toml"))
        .unwrap()
        .replace("3.2.0", "3.3.0");
    std::fs::write(clone.join("Cargo.toml"), toml).unwrap();
    git(&clone, &["commit", "-q", "-am", "Release v3.3.0"]);
    git(&clone, &["push", "-q", "origin", "main"]);
    let out = machine.run(&[], &["release", "cut", "3.4.0"], "").await;
    assert!(!out.status.success());
    assert!(
        text(&out.stderr).contains(
            "the version 3.3.0 on origin/main has no published release. To go on with no release \
             3.3.0, give --skip 3.3.0 --reason TEXT. next: riff release publish v3.3.0"
        ),
        "{}",
        text(&out.stderr)
    );
    assert!(!machine.log().contains("pr create"), "{}", machine.log());
    assert!(!git(&machine.origin(), &["branch"]).contains("release-v"));

    let out = machine
        .ok(
            &[],
            &[
                "release",
                "cut",
                "3.4.0",
                "--skip",
                "3.3.0",
                "--reason",
                "the push of the tag was refused",
            ],
        )
        .await;
    assert!(out.contains("#1140"), "{out}");
    assert!(
        machine
            .log()
            .contains("No release 3.3.0 exists: the push of the tag was refused."),
        "{}",
        machine.log()
    );
}

