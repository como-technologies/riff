//! The release cycle in riff commands (#671, #1949): `riff release cut`
//! (01M7641BHHND5JJA8DGJPFNAN7 to 01M7641T9XH5NAXHE8YKBR4JJY), `verify`
//! (01M5ND0ZNFFAPT1AWD3DP1Y77N), `status` (01M76428NPN7HZCNFCJW8H67RS)
//! and `approve` (01M58B0JMFQ5E40TWTQ48MPSGK), with their guards
//! (01M7641T7FX9416CYY1XKHTJE6, 01M58B0JSQMWNCMSNX19536XT8).
//!
//! The origin is a bare git repository in a folder. A fake `gh` on
//! `PATH` logs each call and the body on its stdin, and answers from a
//! `case` of the test. A real `riff-server` with sign-in holds the
//! lead and the pause. No test reaches GitHub, the real config or the
//! keyring.

use std::path::{Path, PathBuf};
use std::process::{Command, Output, Stdio};

use isolated::Isolated;
use riff::cycle::Refusal;

use crate::book;

fn git(dir: &Path, args: &[&str]) -> String {
    let out = Command::new("git")
        .args(args)
        .current_dir(dir)
        .env("GIT_CONFIG_GLOBAL", "/dev/null")
        .output()
        .unwrap();
    assert!(
        out.status.success(),
        "git {args:?}: {}",
        String::from_utf8_lossy(&out.stderr)
    );
    String::from_utf8_lossy(&out.stdout).trim().to_owned()
}

fn text(out: &[u8]) -> String {
    String::from_utf8_lossy(out).into_owned()
}

/// The root of this repository.
fn top() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

const LOCK: &str = "# This file is automatically @generated by Cargo.\nversion = 4\n\n\
[[package]]\nname = \"riff\"\nversion = \"3.2.0\"\ndependencies = [\n \"serde\",\n]\n\n\
[[package]]\nname = \"riff-server\"\nversion = \"3.2.0\"\n\n\
[[package]]\nname = \"serde\"\nversion = \"1.0.229\"\nsource = \"registry+https://github.com/rust-lang/crates.io-index\"\n";

/// One machine: a clone of a bare origin with the release 3.2.0, a
/// fake `gh`, and a riff-server.
struct Machine {
    env: Isolated,
    root: tempfile::TempDir,
    server: crate::common::Signed,
}

impl Machine {
    /// A machine whose repository has the table `[release]` in `riff.toml`
    /// (01M5SMPX8NM75P8E38DGQ17W7B).
    async fn new() -> Machine {
        Machine::with_config("[release]\n").await
    }

    /// A machine whose repository has the `riff.toml` text `config`.
    async fn with_config(config: &str) -> Machine {
        Machine::on(config, crate::common::start_signed().await).await
    }

    /// As [`Machine::with_config`], at the server `server`.
    async fn on(config: &str, server: crate::common::Signed) -> Machine {
        let root = tempfile::tempdir().unwrap();
        let origin = root.path().join("como-technologies/riff.git");
        std::fs::create_dir_all(&origin).unwrap();
        git(&origin, &["init", "-q", "--bare", "-b", "main"]);
        let clone = root.path().join("clone");
        std::fs::create_dir_all(clone.join("deploy")).unwrap();
        std::fs::create_dir_all(root.path().join("bin")).unwrap();
        git(&clone, &["init", "-q", "-b", "main"]);
        for args in [
            &["config", "user.name", "Test"][..],
            &["config", "user.email", "test@example.com"],
            &["remote", "add", "origin", &origin.to_string_lossy()],
        ] {
            git(&clone, args);
        }
        let write = |name: &str, content: &str| std::fs::write(clone.join(name), content).unwrap();
        write(
            "Cargo.toml",
            "[workspace]\nmembers = [\"crates/*\"]\n\n[workspace.package]\nversion = \"3.2.0\"\n",
        );
        write("Cargo.lock", LOCK);
        write("riff.toml", config);
        for script in ["deploy/release-check.sh", "deploy/artifact-run.sh"] {
            isolated::copy_program(top().join(script), clone.join(script));
        }
        // The release commands build nothing: a cargo that fails and logs
        // shows each call.
        isolated::write_program(
            root.path().join("bin/cargo"),
            "#!/bin/sh\necho \"cargo $*\" >> \"$(dirname \"$0\")/cargo.log\"\nexit 1\n",
        );
        git(&clone, &["add", "-A"]);
        git(&clone, &["commit", "-q", "-m", "Release v3.2.0"]);
        git(&clone, &["tag", "-a", "v3.2.0", "-m", "Release v3.2.0"]);
        write("change.txt", "a change\n");
        git(&clone, &["add", "-A"]);
        git(&clone, &["commit", "-q", "-m", "Show the line (#41)"]);
        git(&clone, &["push", "-q", "origin", "main", "v3.2.0"]);
        let machine = Machine {
            env: Isolated::new(),
            root,
            server,
        };
        machine.fake_gh("");
        machine
    }

    fn clone(&self) -> PathBuf {
        self.root.path().join("clone")
    }

    fn origin(&self) -> PathBuf {
        self.root.path().join("como-technologies/riff.git")
    }

    fn bin(&self) -> PathBuf {
        self.root.path().join("bin")
    }

    fn head(&self) -> String {
        git(&self.clone(), &["rev-parse", "HEAD"])
    }

    /// The git tree of the commit `HEAD` of the clone.
    fn tree(&self) -> String {
        git(&self.clone(), &["rev-parse", "HEAD^{tree}"])
    }

    /// Each call of `cargo`: none, as a release command builds nothing.
    fn cargo_log(&self) -> String {
        std::fs::read_to_string(self.bin().join("cargo.log")).unwrap_or_default()
    }

    /// A fake `gh` that logs `gh ARGS`, copies its stdin for
    /// `--body-file -` and `--notes-file -`, and the file of `--input`,
    /// and answers with `cases` first, then with the facts of the
    /// release 3.2.0.
    fn fake_gh(&self, cases: &str) {
        let head = self.head();
        let merged = format!(
            r#"[{{"number":41,"title":"Show the line","body":"Closes #12\n\nIssue: #12\nMilestone: Wave 34\n","milestone":{{"title":"Wave 34: Release"}},"labels":[],"mergeCommit":{{"oid":"{head}"}}}},{{"number":30,"title":"Old","body":"","milestone":{{"title":"Wave 32"}},"labels":[],"mergeCommit":{{"oid":"0000"}}}}]"#
        );
        isolated::write_program(
            self.bin().join("gh"),
            format!(
                "#!/bin/sh\ndir=$(dirname \"$0\")\necho \"gh $*\" >> \"$dir/gh.log\"\n\
                 case \"$*\" in *'-file -'*) cat >> \"$dir/gh.log\" ;; esac\n\
                 case \"$*\" in *'--input '*) cat \"$7\" >> \"$dir/gh.log\"; echo >> \"$dir/gh.log\" ;; esac\n\
                 case \"$*\" in\n{cases}\n\
                 'release list'*) printf '%s\n' '[{{\"tagName\":\"v3.2.0\"}},{{\"tagName\":\"v3.0.0\"}}]' ;;\n\
                 'api repos/{{owner}}/{{repo}}/milestones'*) printf '%s\n' '[{{\"number\":40,\"title\":\"Wave 34: Release\",\"open_issues\":2,\"closed_issues\":0}},{{\"number\":3,\"title\":\"Backlog\",\"open_issues\":1,\"closed_issues\":0}}]' ;;\n\
                 'issue list'*) printf '%s\n' '[]' ;;\n\
                 'issue create'*) printf '%s\n' 'https://github.com/como-technologies/riff/issues/7' ;;\n\
                 'pr list --state merged --base main'*) printf '%s\n' '{merged}' ;;\n\
                 'pr create'*) printf '%s\n' 'https://github.com/como-technologies/riff/pull/1140' ;;\n\
                 'run list --workflow CI --status waiting'*) printf '%s\n' '[]' ;;\n\
                 'pr list --state open --limit 100'*) printf '%s\n' '[]' ;;\n\
                 'run list --workflow CI --limit'*) printf '%s\n' '[]' ;;\n\
                 'api repos/{{owner}}/{{repo}}/commits/'*) printf '%s\n' '{{\"statuses\":[]}}' ;;\n\
                 esac\nexit 0\n"
            ),
        );
    }

    fn log(&self) -> String {
        std::fs::read_to_string(self.bin().join("gh.log")).unwrap_or_default()
    }

    /// The folder of the riff daemon of this machine.
    fn daemon_dir(&self) -> PathBuf {
        self.env.riff_home().join("daemon")
    }

    /// The daemon of this machine runs the wave of the repository, so a
    /// command registers its watch there (01M5RGCW5NCKQYA61RM63914TX).
    fn serve(&self) {
        let dir = self.daemon_dir();
        std::fs::create_dir_all(&dir).unwrap();
        let wave = riff::wave::Wave {
            repo: "como-technologies/riff".into(),
            main: self.clone(),
            server: self.server.to_string(),
            host: "thelio".into(),
        };
        let waves = std::collections::BTreeMap::from([(wave.repo.clone(), wave)]);
        riff::wave::write_waves(&dir, &waves).unwrap();
    }

    /// The watches in the file of the daemon, but the watch of the wave.
    fn watches(&self) -> Vec<riff::watches::Watch> {
        let all = riff::watches::Watches::new(&self.daemon_dir())
            .read()
            .unwrap();
        all.into_iter()
            .filter(|w| w.op != riff::watches::Op::Wave)
            .collect()
    }

    /// `riff ARGS` in the clone, with the fake `gh` first in `PATH`, and
    /// `vars` in its environment.
    async fn run(&self, vars: &[(&str, &str)], args: &[&str], stdin: &str) -> Output {
        self.run_as("mike", &self.clone(), vars, args, stdin).await
    }

    /// [`Machine::run`] as the user `user` in the folder `dir`.
    async fn run_as(
        &self,
        user: &str,
        dir: &Path,
        vars: &[(&str, &str)],
        args: &[&str],
        stdin: &str,
    ) -> Output {
        let path = format!(
            "{}:{}",
            self.bin().display(),
            std::env::var("PATH").unwrap()
        );
        crate::common::sign_in(&self.server, &self.env.riff_home(), user);
        let mut cmd = self.env.riff();
        cmd.args(args)
            .current_dir(dir)
            .env("RIFF_SERVER", &*self.server)
            .env("RIFF_USER", user)
            .env("RIFF_HOST", "thelio")
            .env("GIT_CONFIG_GLOBAL", "/dev/null")
            .env("PATH", path)
            .env_remove("CLAUDECODE")
            .stdin(Stdio::piped());
        for (key, value) in vars {
            if *key == riff::daemon::SOCKET_VAR {
                test_socket(value);
            }
            if *key == "RIFF_SERVER" && value.is_empty() {
                cmd.env_remove(key);
            } else {
                cmd.env(key, value);
            }
        }
        let stdin = stdin.to_owned();
        tokio::task::spawn_blocking(move || {
            let mut child = cmd
                .stdout(Stdio::piped())
                .stderr(Stdio::piped())
                .spawn()
                .unwrap();
            use std::io::Write;
            child
                .stdin
                .take()
                .unwrap()
                .write_all(stdin.as_bytes())
                .unwrap();
            child.wait_with_output().unwrap()
        })
        .await
        .unwrap()
    }

    async fn ok(&self, vars: &[(&str, &str)], args: &[&str]) -> String {
        let out = self.run(vars, args, "").await;
        assert!(out.status.success(), "riff {args:?}: {}", text(&out.stderr));
        text(&out.stdout)
    }

    /// The person names the session of `vars` the lead, after a first
    /// call of the session (01M5NJAXTQ0YKN7Q7XN0A7ZMPF). The person has
    /// the other `vars`.
    async fn name_lead(&self, vars: &[(&str, &str)]) {
        let id = vars
            .iter()
            .find(|(key, _)| *key == "RIFF_SESSION")
            .unwrap()
            .1;
        self.ok(vars, &["whoami"]).await;
        let person: Vec<(&str, &str)> = vars
            .iter()
            .map(|&(key, value)| (key, if key == "RIFF_SESSION" { "" } else { value }))
            .collect();
        self.ok(&person, &["lead", "--session", id]).await;
    }

    /// The socket path of a container session in the temp folder of
    /// the machine. No daemon listens there.
    fn no_daemon(&self) -> String {
        self.root
            .path()
            .join("run/riff.sock")
            .to_string_lossy()
            .into_owned()
    }
}

/// Refuses a `RIFF_SOCKET` of a test outside the temp folder, for
/// example the real socket of the daemon in a container session
/// (01M5GVK79HV5KSDE626Z5AS1EG).
fn test_socket(path: &str) {
    let path = Path::new(path);
    assert!(
        path != riff::daemon::in_session() && path.starts_with(std::env::temp_dir()),
        "RIFF_SOCKET of a test is not in a temp folder: {}",
        path.display()
    );
}

#[tokio::test]
async fn the_helper_refuses_the_socket_of_the_daemon() {
    let machine = Machine::new().await;
    test_socket(&machine.no_daemon());
    let real = riff::daemon::in_session().to_string_lossy().into_owned();
    let refused = std::panic::catch_unwind(|| test_socket(&real));
    assert!(refused.is_err());
}

/// 01M5SMPX8NM75P8E38DGQ17W7B: a repository with no `[release]` in its
/// `riff.toml` has no release cycle. `riff release cut 1.0.0` refuses with
/// one line. It files no issue, makes no branch, registers no watch, and
/// runs no `gh`.
#[tokio::test]
async fn cut_refuses_a_repository_with_no_release_table_and_makes_no_issue() {
    for config in ["", "[session]\nimage = \"x\"\n"] {
        let machine = Machine::with_config(config).await;
        machine.serve();
        let out = machine.run(&[], &["release", "cut", "1.0.0"], "").await;
        assert!(!out.status.success(), "{out:?}");
        let err = text(&out.stderr);
        assert!(err.contains(riff::text::NO_RELEASE), "{err}");
        assert_eq!(err.trim().lines().count(), 1, "{err}");
        assert!(out.stdout.is_empty(), "{out:?}");
        assert_eq!(machine.log(), "", "the command called gh");
        assert!(!machine.log().contains("issue create"));
        assert!(machine.watches().is_empty());
        let branches = git(&machine.origin(), &["branch", "--list", "release-*"]);
        assert_eq!(branches, "");
    }
}

/// 01M5SMPX8NM75P8E38DGQ17W7B: each subcommand of `riff release` refuses
